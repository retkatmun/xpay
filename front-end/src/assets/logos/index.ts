// Convert SVG string to data URL
function svgToDataUrl(svgString: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svgString)}`;
}

export function getBankLogo(bankName: string): string {
  const key = bankName.toLowerCase().replace(/\s+/g, '').replace('bank', '');
  const svg = BANK_LOGOS[key as keyof typeof BANK_LOGOS] || BANK_LOGOS.access;
  return svgToDataUrl(svg);
}

export function getNetworkLogo(networkName: string): string {
  const key = networkName.toLowerCase().replace(/\s+/g, '').replace('chain', '');
  const svg = NETWORK_LOGOS[key as keyof typeof NETWORK_LOGOS] || NETWORK_LOGOS.ethereum;
  return svgToDataUrl(svg);
}

export function getTokenLogo(tokenSymbol: string): string {
  const key = tokenSymbol.toLowerCase();
  const svg = TOKEN_LOGOS[key as keyof typeof TOKEN_LOGOS] || TOKEN_LOGOS.usdc;
  return svgToDataUrl(svg);
}
